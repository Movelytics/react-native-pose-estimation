/**
 * Writes src/sdkVersion.ts from package.json so handshake SDK_VERSION
 * never drifts from the published package version.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const version = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version;
if (typeof version !== 'string' || !version) {
  console.error('package.json missing version');
  process.exit(1);
}
const out = join(root, 'src/sdkVersion.ts');
writeFileSync(
  out,
  [
    '/** AUTO-GENERATED by scripts/sync-sdk-version.mjs — do not edit. */',
    `export const SDK_VERSION = '${version}';`,
    '',
  ].join('\n'),
);
console.log(`sdkVersion → ${version}`);
